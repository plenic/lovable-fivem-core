export const createInitialSlots = (): InventorySlot[] => {
  const slots: InventorySlot[] = [];
  
  // Create 40 slots (8 columns x 5 rows)
  for (let i = 0; i < 40; i++) {
    slots.push({
      slotId: i,
      item: i < sampleItems.length ? { ...sampleItems[i] } : null,
    });
  }
  
  return slots;
};

